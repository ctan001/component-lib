# font_cn.py — 16x16 Chinese character bitmaps
# Format: MONO_HMSB (MicroPython), bit0=leftmost pixel
# Characters: 唐嘉瑞

FONT = {
    "唐": bytes([0x80, 0x00, 0x00, 0x01, 0xFC, 0x7F, 0x04, 0x01, 0xF4, 0x1F, 0x04, 0x11, 0xFC, 0x7F, 0x04, 0x11, 0xF4, 0x1F, 0x04, 0x01, 0xF4, 0x1F, 0x14, 0x10, 0x12, 0x10, 0x12, 0x10, 0xF1, 0x1F, 0x10, 0x10]),
    "嘉": bytes([0x80, 0x00, 0xFF, 0x7F, 0x80, 0x00, 0xFC, 0x1F, 0x00, 0x00, 0xF8, 0x0F, 0x08, 0x08, 0xF8, 0x0F, 0x10, 0x04, 0xFF, 0x7F, 0x08, 0x00, 0xFE, 0x3E, 0x88, 0x22, 0x84, 0x22, 0xA2, 0x3E, 0x41, 0x22]),
    "瑞": bytes([0x00, 0x04, 0x40, 0x44, 0x5F, 0x44, 0x44, 0x44, 0xC4, 0x7F, 0x04, 0x00, 0xE4, 0x7F, 0x1F, 0x04, 0x04, 0x02, 0xC4, 0x7F, 0x44, 0x4A, 0x5C, 0x4A, 0x47, 0x4A, 0x42, 0x4A, 0x40, 0x4A, 0x40, 0x60]),
}

W = 16
H = 16

def draw(fb, ch, x, y, col=1):
    import framebuf
    if ch not in FONT:
        return
    src = framebuf.FrameBuffer(bytearray(FONT[ch]), W, H, framebuf.MONO_HMSB)
    fb.blit(src, x, y, -1 if col else 0)

def draw_str(fb, text, x, y, col=1):
    for ch in text:
        draw(fb, ch, x, y, col)
        x += W