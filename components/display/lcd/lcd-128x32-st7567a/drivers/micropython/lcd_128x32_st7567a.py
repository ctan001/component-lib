class LCD128x32:
    WIDTH  = 128
    PAGES  = 4
    ADDR   = 0x3F

    def __init__(self, sda=4, scl=5, addr=0x3F):
        self._i2c = SoftI2C(sda=Pin(sda), scl=Pin(scl), freq=100_000)
        self._addr = addr
        self._cursor = [0, 0]
        self._init()

    def _cmd(self, b):
        self._i2c.writeto(self._addr, bytes([0x00, b]))

    def _init(self):
        self._cmd(0xE2)  # restart
        self._cmd(0xA3)  # bias 1/7
        self._cmd(0xA0)  # SEG normal
        self._cmd(0xC8)  # COM reverse
        self._cmd(0x22)  # regulation ratio
        self._cmd(0x81)  # EV command
        self._cmd(0x30)  # EV value
        self._cmd(0x2C)  # booster ON
        self._cmd(0x2E)  # regulator ON
        self._cmd(0x2F)  # follower ON
        self.Clear()
        self._cmd(0xFF)  # enter extension command set
        self._cmd(0x72)  # DSM ON (1/33 duty)
        self._cmd(0xFE)  # exit extension command set
        self._cmd(0xD6)  # display duty = 33
        self._cmd(0x90)  # BA = 1/9
        self._cmd(0x9D)  # frame rate
        self._cmd(0xAF)  # display ON
        self._cmd(0x40)  # start line = 0

    def Clear(self):
        for page in range(self.PAGES):
            self._cmd(0xB0 | page)
            self._cmd(0x10)
            self._cmd(0x00)
            d = bytearray(self.WIDTH + 1)
            d[0] = 0x40
            self._i2c.writeto(self._addr, d)

    def Cursor(self, row, col):
        self._cursor[0] = min(row, 3)
        self._cursor[1] = min(col, 17)

    def Display(self, text):
        row, col = self._cursor
        x = col * 7
        self._cmd(0xB0 | row)
        self._cmd(0x10 | (x >> 4))
        self._cmd(0x00 | (x & 0x0F))
        for ch in text:
            idx = _CHAR_MAP.get(ch, 87)  # default space
            glyph = _FONT[idx]
            d = bytearray(8)
            d[0] = 0x40
            d[1:] = bytes(glyph)
            self._i2c.writeto(self._addr, d)

    def BigDisplay(self, text, x_start=0):
        """Render text at 4x scale across all 4 pages (fills 32-pixel height)."""
        x = x_start
        for ch in text:
            idx = _CHAR_MAP.get(ch, 87)
            glyph = _FONT[idx]
            for col_i in range(7):
                b = glyph[col_i]
                # Expand 8 original bits → 4 page-bytes (2 bits each → 4 rows each)
                pb = [((b >> (p * 2)) & 1) * 0x0F | (((b >> (p * 2 + 1)) & 1) * 0xF0)
                      for p in range(4)]
                # Write column 4 times (4x width)
                for rep in range(4):
                    xp = x + col_i * 4 + rep
                    if xp >= self.WIDTH:
                        return
                    for page in range(4):
                        self._cmd(0xB0 | page)
                        self._cmd(0x10 | (xp >> 4))
                        self._cmd(0x00 | (xp & 0x0F))
                        self._i2c.writeto(self._addr, bytes([0x40, pb[page]]))
            x += 28  # 7 cols * 4 = 28 px per char
